using System.Diagnostics;
using System.Net;
using System.Security.Cryptography;
using Channeled.Application.Abstractions.Storage;
using Channeled.Domain.Identity;
using Channeled.Domain.Storage;
using Channeled.Domain.Teams;
using Channeled.Infrastructure.Files;
using FluentAssertions;
using Microsoft.Extensions.DependencyInjection;
using static Channeled.Tests.Api.DownloadHelpers;

namespace Channeled.Tests.Api;

/// <summary>
/// Downloads must stream end to end: a 2 GiB file through the ticket endpoint keeps process memory flat
/// (mirrors the upload gate; size via CHANNELED_GATE_DOWNLOAD_BYTES).
/// </summary>
[Collection("Api")]
public class DownloadStreamingMemoryTests(DownloadApiFactory factory) : TeamPrivacyTestBase(factory), IClassFixture<DownloadApiFactory>
{
    private const long MaxGrowthBytes = 64L * 1024 * 1024;

    private static long GateBytes =>
        long.TryParse(Environment.GetEnvironmentVariable("CHANNELED_GATE_DOWNLOAD_BYTES"), out var n) && n > 0
            ? n
            : 2L * 1024 * 1024 * 1024;

    [Fact]
    public async Task Large_ticket_download_streams_without_buffering()
    {
        var channel = await CreateChannelAsync("general", ChannelVisibility.Everyone);
        var size = GateBytes;
        var fileId = UuidV7.NewGuid();
        var key = ObjectKey.ForFile(fileId);
        var store = Factory.Services.GetRequiredService<IFileStore>();
        await using (var source = new PatternStream(size))
        {
            await store.PutAsync(key, source, "application/octet-stream");
            var now = DateTimeOffset.UtcNow;
            await DbAsync(async db =>
            {
                db.Files.Add(new FileEntity
                {
                    Id = fileId,
                    ChannelId = channel.Id,
                    Name = "huge.bin",
                    ContentType = "application/octet-stream",
                    SizeBytes = size,
                    Sha256 = source.Sha256Hex(),
                    StorageKey = key,
                    UploadedBy = Owner.Id,
                    CreatedAt = now,
                    UpdatedAt = now,
                });
                await db.SaveChangesAsync();
            });
        }

        var url = await TicketUrlAsync(Owner.Client, Channel(Slug, "general", fileId));
        GC.Collect(2, GCCollectionMode.Forced, blocking: true, compacting: true);
        var baseline = Process.GetCurrentProcess().WorkingSet64;
        var peak = baseline;

        using var response = await GetAsync(Owner.Client, url, completion: HttpCompletionOption.ResponseHeadersRead);
        response.StatusCode.Should().Be(HttpStatusCode.OK);
        response.Content.Headers.ContentLength.Should().Be(size);
        await using var body = await response.Content.ReadAsStreamAsync();
        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        var buffer = new byte[256 * 1024];
        long received = 0;
        int read;
        while ((read = await body.ReadAsync(buffer)) > 0)
        {
            hash.AppendData(buffer, 0, read);
            received += read;
            if ((received & ((64L << 20) - 1)) < read)
            {
                peak = Math.Max(peak, Process.GetCurrentProcess().WorkingSet64);
            }
        }

        peak = Math.Max(peak, Process.GetCurrentProcess().WorkingSet64);
        received.Should().Be(size);
        Convert.ToHexString(hash.GetHashAndReset()).ToLowerInvariant().Should().Be(await ShaOfPatternAsync(size));
        (peak - baseline).Should().BeLessThan(MaxGrowthBytes, "downloads must stream, not buffer");
    }

    private static async Task<string> ShaOfPatternAsync(long size)
    {
        await using var stream = new PatternStream(size);
        await stream.CopyToAsync(Stream.Null);
        return stream.Sha256Hex();
    }

    /// <summary>Deterministic generated bytes (never materialized) that also hashes what it yields.</summary>
    private sealed class PatternStream(long length) : Stream
    {
        private readonly IncrementalHash _hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        private long _position;
        private string? _sha;

        public string Sha256Hex() => _sha ??= Convert.ToHexString(_hash.GetHashAndReset()).ToLowerInvariant();

        public override int Read(byte[] buffer, int offset, int count)
        {
            var n = (int)Math.Min(count, length - _position);
            for (var i = 0; i < n; i++)
            {
                var p = _position + i;
                buffer[offset + i] = (byte)((p * 31) ^ (p >> 13));
            }

            _hash.AppendData(buffer, offset, n);
            _position += n;
            return n;
        }

        public override bool CanRead => true;
        public override bool CanSeek => false;
        public override bool CanWrite => false;
        public override long Length => length;
        public override long Position { get => _position; set => throw new NotSupportedException(); }
        public override void Flush() { }
        public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
        public override void SetLength(long value) => throw new NotSupportedException();
        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();

        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                _hash.Dispose();
            }

            base.Dispose(disposing);
        }
    }
}
